# Generates app/theme-dark-generated.css: dark-theme overrides for hard-coded light colors in app/globals.css.
# Re-run after editing globals.css:  python3 scripts/dev/gen-dark-css.py
import re
css = open('app/globals.css').read()
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
BG = r'(white|#fff\b|#ffffff|#fafafa|#f8fafc|#f8f9fc|#f4f6fb|#f1f5f9|#f9fafb|#f3f4f6|#eef2ff|#fdf2f8|#faf5ff|#f5f3ff|oklch\(1 0 0\)|rgba\(255,\s*255,\s*255,\s*0?\.[6-9]\d*\))'
TXT = {
    '#0f172a': 'var(--label)', '#111827': 'var(--label)', '#1e293b': 'var(--label)', '#1f2937': 'var(--label)',
    '#334155': 'var(--label-2)', '#374151': 'var(--label-2)', '#475569': 'var(--label-3)',
    '#64748b': 'var(--secondary)', '#6b7280': 'var(--secondary)', '#94a3b8': 'var(--faint)', '#9ca3af': 'var(--faint)',
}
BORDER = r'#e2e8f0|#e5e7eb|#f1f5f9|#eef2f7|#e8eaf0|#edf0f5|#f3f4f6|#cbd5e1|#d1d5db'
out = []
def is_light(value):
    # every colour in the value is near-white (light hex, white, light rgba) and there is at least one
    cols = re.findall(r'#([0-9a-f]{6}|[0-9a-f]{3})\b|rgba?\(([^)]*)\)|\b(white)\b', value)
    if not cols or 'url(' in value: return False
    for hx, rgb, w in cols:
        if w: continue
        if hx:
            if len(hx) == 3: hx = ''.join(c * 2 for c in hx)
            ch = [int(hx[i:i + 2], 16) for i in (0, 2, 4)]
        else:
            parts = [x.strip() for x in rgb.split(',')]
            ch = [float(x) for x in parts[:3]]
            if len(parts) > 3 and float(parts[3]) < 0.5: continue  # mostly transparent — ignore
        if min(ch) < 236: return False
    return True
def walk(text, prefix=''):
    i = 0
    while i < len(text):
        j = text.find('{', i)
        if j < 0: break
        sel = ' '.join(text[i:j].split())
        depth, k = 1, j + 1
        while depth and k < len(text):
            depth += {'{': 1, '}': -1}.get(text[k], 0); k += 1
        body = text[j + 1:k - 1]
        if sel.startswith('@media') or sel.startswith('@supports'):
            sub = []
            out_len = len(out); walk(body, sel)
        elif all(re.fullmatch(r'[a-z]+(::?[a-z-]+)?', x.strip()) and '::placeholder' not in x for x in sel.split(',')):
            pass  # bare element selectors (button, input…) — theme-app.css handles them in @layer base
        elif not sel.startswith('@') and sel not in (':root', '*', 'html', 'body') and '%' not in sel and sel not in ('from', 'to'):
            decl = []
            b = body.lower()
            m = re.search(r'background(-color)?\s*:\s*([^;]+)', b)
            if m and (re.match(BG, m.group(2).strip()) or is_light(m.group(2))): decl.append('background: var(--cell)')
            m = re.search(r'(?:^|;|\s)color\s*:\s*(#[0-9a-f]{6})', b)
            if m and m.group(1) in TXT: decl.append('color: ' + TXT[m.group(1)])
            m = re.search(r'(border(?:-top|-bottom|-left|-right)?)\s*:\s*([^;]*?)(' + BORDER + ')', b)
            if m: decl.append(m.group(1) + '-color: var(--sep)')
            if decl:
                sels = ', '.join('html[data-theme="dark"] ' + s.strip() for s in sel.split(','))
                rule = sels + ' { ' + '; '.join(d + ' !important' for d in decl) + '; }'
                out.append((prefix, rule))
        i = k
walk(css)
lines = ['/* AUTO-GENERATED by scripts/dev/gen-dark-css.py from globals.css — do not edit by hand */']
cur = None
for prefix, rule in out:
    if prefix != cur:
        if cur: lines.append('}')
        if prefix: lines.append(prefix + ' {')
        cur = prefix
    lines.append(rule)
if cur: lines.append('}')
open('app/theme-dark-generated.css', 'w').write('\n'.join(lines) + '\n')
print(len(out), 'rules')
